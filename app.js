const plural = (n, one, few, many) => {
  const d = n % 10;
  const t = n % 100;
  if (d === 1 && t !== 11) return one;
  if (d >= 2 && d <= 4 && (t < 12 || t > 14)) return few;
  return many;
};
const bar = (count, total, label) =>
  `<div class="progress-bar" role="progressbar" aria-valuemin="0" aria-valuemax="${total}" aria-valuenow="${count}" aria-label="${label}"><span style="width:${(count / total) * 100}%"></span></div>`;

function route() {
  const hash = location.hash.replace(/^#\/?/, '');
  const old = hash.match(/^urok-(\d+)/);
  if (old && OLD_LINKS[old[1]]) {
    location.replace(`#/${OLD_LINKS[old[1]]}`);
    return;
  }
  const [mId, lId, stepNo] = hash.split('/');
  const m = MODULES.find((x) => x.id === mId);
  if (m && lId) {
    const li = m.lessons.findIndex((x) => x.id === lId);
    if (li >= 0) return renderLesson(m, li, Math.max(0, Number(stepNo || 1) - 1));
  }
  if (m) return renderModule(m);
  renderHome();
}

