let current = null; // { m, li, step, screenKey, seen }

function renderLesson(m, li, step) {
  const lesson = m.lessons[li];
  document.title = `${lesson.title} — Посібник адмінпанелі`;
  app.innerHTML = `
    <div class="wrap lesson">
      <nav class="crumbs">${rootCrumb(m)}<span>/</span><a href="#/${m.id}">${h(m.title)}</a></nav>
      <p class="eyebrow">Урок ${li + 1} з ${m.lessons.length}</p>
      <h1>${h(lesson.title)}</h1>
      <div class="lesson-grid">
        <div class="phone" id="device"><div class="screen" id="screen"></div></div>
        <div class="panel" id="panel" aria-live="polite"></div>
      </div>
    </div>`;
  current = { m, li, step: 0, screenKey: null, seen: new Set([0]) };
  show(Math.min(step, lesson.steps.length));
  app.focus({ preventScroll: true });
  window.scrollTo(0, 0);
}

const lessonOf = () => current.m.lessons[current.li];

function show(step) {
  const lesson = lessonOf();
  current.step = step;
  current.seen.add(step);
  const isQuiz = step >= lesson.steps.length;
  const s = lesson.steps[Math.min(step, lesson.steps.length - 1)];
  drawScreen(s, isQuiz ? -1 : step);
  history.replaceState(null, '', `#/${current.m.id}/${lesson.id}${step ? `/${step + 1}` : ''}`);

  const panel = document.getElementById('panel');
  const dots = lesson.steps
    .map(
      (_, i) =>
        `<button class="dot ${i === step ? 'active' : current.seen.has(i) ? 'seen' : ''}" data-go="${i}" aria-label="Крок ${i + 1}"></button>`,
    )
    .join('');
  const quizDot = `<button class="dot quiz-dot ${isQuiz ? 'active' : ''}" data-go="${lesson.steps.length}" aria-label="Перевірка"></button>`;

  if (!isQuiz) {
    panel.innerHTML = `
      <div class="step-count">Крок ${step + 1} з ${lesson.steps.length}</div>
      <div class="dots">${dots}${quizDot}</div>
      <h2>${s.title}</h2>
      <p class="text">${s.text}</p>
      <div class="nav">
        <button class="btn btn-ghost" data-go="${step - 1}" ${step === 0 ? 'disabled' : ''}>← Назад</button>
        <button class="btn btn-primary" data-go="${step + 1}">${step === lesson.steps.length - 1 ? 'Перевірити себе' : 'Далі'} →</button>
      </div>
      <p class="kbd-hint">Порада: стрілки ← → на клавіатурі теж працюють.</p>`;
  } else {
    const qz = lesson.quiz;
    // Shown in a fresh random order each time, so the right answer's place
    // gives nothing away; data-answer keeps each option's index in `options`.
    const order = qz.options.map((_, i) => i);
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [order[i], order[j]] = [order[j], order[i]];
    }
    panel.innerHTML = `
      <div class="step-count">Перевірте себе</div>
      <div class="dots">${dots}${quizDot}</div>
      <h2>${h(qz.q)}</h2>
      <div class="options">
        ${order.map((i) => `<button class="option" data-answer="${i}">${h(qz.options[i])}</button>`).join('')}
      </div>
      <p class="feedback" hidden></p>
      <div class="nav"><button class="btn btn-ghost" data-go="${step - 1}">← Назад</button></div>`;
  }
}

function finishLesson() {
  const { m, li } = current;
  done.add(lessonKey(m, m.lessons[li]));
  saveDone();
  const panel = document.getElementById('panel');
  const box = document.createElement('div');
  box.className = 'done-box';
  if (li + 1 < m.lessons.length) {
    const next = m.lessons[li + 1];
    box.innerHTML = `<p><b>Урок пройдено.</b> Далі: «${h(next.title)}».</p><a class="btn btn-primary" href="#/${m.id}/${next.id}">Наступний урок →</a>`;
  } else if (bundleFor(m)) {
    const b = bundleFor(m);
    const i = b.modules.indexOf(m.id);
    const nextModule = i >= 0 && mod(b.modules[i + 1]);
    box.innerHTML = nextModule
      ? `<p><b>Модуль «${h(m.title)}» пройдено!</b> Далі — «${h(nextModule.title)}».</p><a class="btn btn-primary" href="#/${nextModule.id}/${nextModule.lessons[0].id}">Наступний урок →</a>`
      : `<p><b>Модуль «${h(m.title)}» пройдено!</b>${i >= 0 ? ' Це останній модуль для вашої ролі.' : ''}</p><a class="btn btn-primary" href="#/for/${b.id}">До ваших уроків</a>`;
  } else {
    const mi = MODULES.indexOf(m);
    const nextModule = MODULES.slice(mi + 1).find((x) => moduleDone(x) < x.lessons.length);
    box.innerHTML = nextModule
      ? `<p><b>Модуль «${h(m.title)}» пройдено!</b> Далі можна взятися за «${h(nextModule.title)}» — якщо він для вашої ролі.</p><a class="btn btn-primary" href="#/${nextModule.id}">До модуля «${h(nextModule.title)}» →</a>`
      : `<p><b>Модуль «${h(m.title)}» пройдено!</b></p><a class="btn btn-primary" href="#/">До всіх модулів</a>`;
  }
  panel.querySelector('.nav').replaceWith(box);
}

function drawScreen(s, activeStep) {
  const screenEl = document.getElementById('screen');
  const device = document.getElementById('device');
  const lesson = lessonOf();
  const scr = SCREENS[s.screen];
  const w = scr.w || 780;

  if (current.screenKey !== s.screen) {
    current.screenKey = s.screen;
    device.className = scr.device === 'laptop' ? 'phone laptop' : 'phone';
    if (scr.mock) {
      screenEl.innerHTML = MOCKS[scr.mock]();
    } else {
      const onThis = lesson.steps.map((st, i) => ({ st, i })).filter(({ st }) => st.screen === s.screen);
      const spots = onThis
        .filter(({ st }) => st.spot)
        .map(
          ({ st, i }) =>
            `<button class="spot${st.spot[0] > w * 0.77 ? ' badge-left' : ''}" data-go="${i}" style="left:${(st.spot[0] / w) * 100}%;top:${(st.spot[1] / scr.h) * 100}%" aria-label="Крок ${i + 1}: ${h(st.title)}"><span>${i + 1}</span></button>`,
        )
        .join('');
      // A whole section is outlined rather than pointed at; only the active one shows.
      const areas = onThis
        .filter(({ st }) => st.area)
        .map(({ st, i }) => {
          const [x, y, aw, ah] = st.area;
          return `<div class="area" data-step="${i}" style="left:${(x / w) * 100}%;top:${(y / scr.h) * 100}%;width:${(aw / w) * 100}%;height:${(ah / scr.h) * 100}%"><span>${i + 1}</span></div>`;
        })
        .join('');
      screenEl.innerHTML = `<div class="canvas"><img src="${scr.src}" alt="${h(scr.alt)}" width="${w}" height="${scr.h}">${areas}${spots}</div>`;
    }
  }

  if (scr.mock) {
    screenEl.querySelectorAll('[data-focus]').forEach((el) => el.classList.toggle('active', activeStep >= 0 && el.dataset.focus === s.focus));
    positionCanvas();
    return;
  }
  screenEl.querySelectorAll('.spot').forEach((b) => b.classList.toggle('active', Number(b.dataset.go) === activeStep));
  screenEl.querySelectorAll('.area').forEach((a) => a.classList.toggle('active', Number(a.dataset.step) === activeStep));
  positionCanvas();
}

// Slide the screenshot so the active spot sits a little above the middle;
// scale a mock-up (laid out at 390 px) to the screen's width.
function positionCanvas() {
  if (!current) return;
  const screenEl = document.getElementById('screen');
  if (!screenEl) return;
  screenEl.style.setProperty('--k', screenEl.clientWidth / 390);
  const canvas = screenEl.querySelector('.canvas');
  if (!canvas) return;
  const lesson = lessonOf();
  const s = lesson.steps[Math.min(current.step, lesson.steps.length - 1)];
  const scr = SCREENS[s.screen];
  const w = scr.w || 780;
  const sw = screenEl.clientWidth;
  const sh = screenEl.clientHeight;
  const ch = (sw * scr.h) / w;
  const k = ch / scr.h;
  let target = 0;
  if (s.spot) target = s.spot[1] * k - sh * 0.42;
  if (s.area) {
    const top = s.area[1] * k;
    const height = s.area[3] * k;
    // Centre an area that fits; otherwise show its top with a little room above.
    target = height < sh * 0.84 ? top + height / 2 - sh / 2 : top - sh * 0.06;
  }
  const off = Math.max(0, Math.min(target, ch - sh));
  canvas.style.transform = `translateY(${-off}px)`;
}

